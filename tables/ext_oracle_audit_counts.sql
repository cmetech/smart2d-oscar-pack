CREATE TABLE ext_oracle_audit_counts (
    id CHAR(36) NOT NULL PRIMARY KEY,
    audit_type VARCHAR(255) DEFAULT NULL,
    sessionid BIGINT DEFAULT NULL,
    os_username VARCHAR(255) DEFAULT NULL,
    userhost VARCHAR(255) DEFAULT NULL,
    terminal VARCHAR(255) DEFAULT NULL,
    authentication_type VARCHAR(255) DEFAULT NULL,
    dbusername VARCHAR(255) DEFAULT NULL,
    client_program_name VARCHAR(255) DEFAULT NULL,
    object_schema VARCHAR(255) DEFAULT NULL,
    object_name VARCHAR(255) DEFAULT NULL,
    sql_text MEDIUMTEXT DEFAULT NULL,
    sql_binds TEXT DEFAULT NULL,
    event_timestamp VARCHAR(255) NOT NULL,
    action_name VARCHAR(255) DEFAULT NULL,
    instance VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_ext_oracle_audit_event_ts (event_timestamp),
    INDEX idx_ext_oracle_audit_dbuser_action (dbusername, action_name),
    INDEX idx_ext_oracle_audit_object (object_schema, object_name),
    INDEX idx_ext_oracle_audit_created (created_at)
) ENGINE=InnoDB;
